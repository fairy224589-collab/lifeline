"use client";

import { useRef } from "react";
import { useInView, useProgress } from "@/lib/useReveal";

/**
 * AI Copilot — a CONCEPT. The prototype has no AI feature, so this section says so plainly.
 * The satellite nodes are the five factors the existing matching engine really computes.
 */
const FACTORS = ["Urgency", "Compatibility", "Proximity", "Expiry", "Reliability"];

export default function CopilotSection() {
  const ref = useRef<HTMLElement>(null);
  const seen = useInView(ref, 0.25);
  const p = useProgress(seen, "copilot", 1600);
  const cx = 150, cy = 150, R = 105;
  return (
    <section id="ai-copilot" ref={ref} className="scroll-mt-24">
      <div className="cp-grid">
        <div className="space-y-4">
          <p className="font-mono text-[10px] font-semibold uppercase tracking-widest text-blood">AI Copilot</p>
          <h2 className="font-display text-3xl font-semibold text-ink sm:text-4xl leading-tight">Decision support, <em className="text-blood">explained.</em></h2>
          <p className="cp-badge"><span aria-hidden="true" />Concept · not implemented in this prototype</p>
          <p className="text-sm text-ink-60 leading-relaxed">LifeLine&rsquo;s matching engine already weighs urgency, compatibility, proximity, expiry and reliability. A copilot could sit on top and put that reasoning into plain language, and flag unusual requests for a person to review.</p>
          <p className="text-sm text-ink-60 leading-relaxed">Nothing on this page is generated by an AI model. The diagram shows the five factors that exist today; the assistant is an idea for future work.</p>
          <div className="cp-mock" aria-label="Illustrative mock-up, not real output">
            <p className="cp-mock-l">Illustrative mock-up · static text</p>
            <p>“Ranked first: compatible blood group, closest source, stock nearing expiry.”</p>
          </div>
        </div>
        <figure className="cp-art">
          <svg viewBox="0 0 300 300" role="img" aria-label="A central copilot node connected to five decision factors">
            {FACTORS.map((f, i) => { const a = (-90 + i * 72) * Math.PI / 180, x = cx + R * Math.cos(a), y = cy + R * Math.sin(a); const lp = Math.max(0, Math.min(1, p * 1.5 - i * 0.12)); return (
              <g key={f}>
                <line x1={cx} y1={cy} x2={x} y2={y} stroke="#C9304B" strokeWidth="1.2" pathLength={1} strokeDasharray="1" strokeDashoffset={1 - lp} opacity=".75" />
                {lp >= 1 && <circle r="2.6" fill="#C9304B"><animateMotion dur={`${2.4 + i * 0.3}s`} repeatCount="indefinite" path={`M${cx} ${cy} L${x} ${y}`} /></circle>}
                <circle cx={x} cy={y} r="17" fill="#fff" stroke="#7A1F2B" strokeWidth="1.4" opacity={lp} />
                <text x={x} y={y + 3} textAnchor="middle" className="cp-t" opacity={lp}>{f[0]}</text>
                <text x={x} y={y + (y > cy ? 32 : -24)} textAnchor="middle" className="cp-l" opacity={lp}>{f.toUpperCase()}</text>
              </g>); })}
            <circle cx={cx} cy={cy} r={26 + 4 * Math.sin(p * 6)} fill="rgba(201,48,75,.12)" />
            <circle cx={cx} cy={cy} r="21" fill="#7A1F2B" />
            <path d="M150 140 L153 147 L160 150 L153 153 L150 160 L147 153 L140 150 L147 147Z" fill="#FAF7F2" />
          </svg>
        </figure>
      </div>
    </section>
  );
}
